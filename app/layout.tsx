import type { Metadata } from "next"
import { Inter } from "next/font/google"
import { Providers } from "./providers"

import "./global.css"
import { getQueryClient } from "./providers/tanstack/get-query-client"
import { getCompressedPlaces } from "./todo/utils/compressedPlaces"
import { data } from "./todo/data"
import { dehydrate, HydrationBoundary } from "@tanstack/react-query"

const inter = Inter({ subsets: ["latin"] })

export const metadata: Metadata = {
	title: "Create Next App",
	description: "Generated by create next app",
}

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms))

export default function RootLayout({
	children,
}: Readonly<{
	children: React.ReactNode
}>) {
	const queryClient = getQueryClient()

	queryClient.prefetchQuery({
		queryKey: ["compressed-places"],
		queryFn: async () => {
			await sleep(3000)
			return getCompressedPlaces(data)
		},
	})

	return (
		<html lang="en">
			<body className={inter.className} style={{ fontWeight: 300 }}>
				<Providers>
					<HydrationBoundary state={dehydrate(queryClient)}>
						{children}
					</HydrationBoundary>
				</Providers>
			</body>
		</html>
	)
}
