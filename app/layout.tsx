import type { Metadata } from "next"
import { Inter } from "next/font/google"
import { Providers } from "./providers"

import "./global.css"
import { getQueryClient } from "./providers/tanstack/getQueryClient"
import { getCompressedPlaces } from "./utils/compressedPlaces"
import { data } from "./data"
import { dehydrate, HydrationBoundary } from "@tanstack/react-query"
import { styled } from "restyle"
import { MapServer } from "components/Map/Server"

const inter = Inter({ subsets: ["latin"] })

export const metadata: Metadata = {
	title: "Create Next App",
	description: "Generated by create next app",
}

const compressedPlaces = getCompressedPlaces(data)

export default function RootLayout({
	children,
}: Readonly<{
	children: React.ReactNode
}>) {
	const queryClient = getQueryClient()

	queryClient.prefetchQuery({
		queryKey: ["compressed-places"],
		queryFn: async () => compressedPlaces,
	})

	return (
		<html lang="en">
			<body
				className={inter.className}
				style={{ fontWeight: 300 }}
				// for theme cookie
				suppressHydrationWarning
			>
				<Providers>
					<HydrationBoundary state={dehydrate(queryClient)}>
						<Application>
							<MapServer />
							{children}
						</Application>
					</HydrationBoundary>
				</Providers>
			</body>
		</html>
	)
}

const Application = styled("div", {
	width: "100dvw",
	height: "100dvh",
	overflow: "clip",
	display: "grid",
	gridTemplateColumns: "1fr 1fr 1fr",
	placeItems: "start stretch",
})
